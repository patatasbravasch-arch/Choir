import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { guideGetAssetEntries, guideBuildMarkdown } from '../src/setup-guides.js';
const root = new URL('../', import.meta.url);
const manifest = JSON.parse(readFileSync(new URL('spindle.json', root), 'utf8'));
mkdirSync(new URL('dist/', root), { recursive: true });
const core = readFileSync(new URL('src/core.js', root), 'utf8').replace(/^export /gm, '');
const guides = readFileSync(new URL('src/setup-guides.js', root), 'utf8').replace(/^export /gm, '');
const setupUi = readFileSync(new URL('src/setup-ui.js', root), 'utf8').replace(/^export /gm, '');
const setup = readFileSync(new URL('src/setup.js', root), 'utf8').replace(/^import .* from '\.\/setup-(?:guides|ui)\.js';\r?\n/gm, '').replace(/^export /gm, '');
// The same illustrations ship inside the frontend for offline setup and as
// ordinary SVGs for the shareable Markdown guide.
mkdirSync(new URL('assets/guides/', root), {recursive:true});
for(const asset of guideGetAssetEntries()){
  writeFileSync(new URL(`assets/guides/${asset.fileName}`, root), asset.svg);
}
mkdirSync(new URL('docs/', root), {recursive:true});
writeFileSync(new URL('docs/setup-guides.md', root), guideBuildMarkdown());
const theme = readFileSync(new URL('src/abyssal-theme.js', root), 'utf8').replace(/^export /gm, '');
const playedAudio = readFileSync(new URL('src/played-audio.js', root), 'utf8').replace(/^export /gm, '');
const drawerUi = readFileSync(new URL('src/drawer-ui.js', root), 'utf8').replace(/^export /gm, '');
const delivery = readFileSync(new URL('src/delivery.js', root), 'utf8').replace(/^export /gm, '');
for (const target of ['backend', 'frontend']) {
  let entry = readFileSync(new URL(`src/${target}.js`, root), 'utf8').replace(/^import .* from '\.\/core\.js';\r?\n/gm, '');
  entry = entry.replaceAll("'__CHOIR_VERSION__'", JSON.stringify(manifest.version));
  entry = entry.replace(/^import .* from '\.\/setup\.js';\r?\n/gm, '');
  entry = entry.replace(/^import .* from '\.\/abyssal-theme\.js';\r?\n/gm, '');
  entry = entry.replace(/^import .* from '\.\/played-audio\.js';\r?\n/gm, '');
  entry = entry.replace(/^import .* from '\.\/(?:delivery|drawer-ui)\.js';\r?\n/gm, '');
  if (target === 'backend') {
    entry = entry.replace(/^export /gm, '');
  }
  writeFileSync(new URL(`dist/${target}.js`, root), `// Generated by scripts/build.mjs. Edit src/, then rebuild.\n${core}\n${target === 'frontend' ? guides + '\n' + setupUi + '\n' + setup + '\n' + theme + '\n' + playedAudio + '\n' + drawerUi + '\n' + delivery + '\n' : ''}${entry}`);
  console.log(`Built ${fileURLToPath(new URL(`dist/${target}.js`, root))}`);
}
